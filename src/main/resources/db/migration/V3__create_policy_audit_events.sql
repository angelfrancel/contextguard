CREATE TABLE policy_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    tool_name VARCHAR(64) NOT NULL,
    outcome VARCHAR(16) NOT NULL
        CHECK (outcome IN ('ALLOW', 'REDACT', 'BLOCK')),
    detection_count INTEGER NOT NULL CHECK (detection_count >= 0),
    snapshot_version BIGINT NOT NULL CHECK (snapshot_version > 0)
);

CREATE INDEX idx_policy_audit_events_occurred_at
    ON policy_audit_events (occurred_at);
